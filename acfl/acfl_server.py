class ACFLServerTimeSeries(FLServerTimeSeries):
  """Federated Learning Server with ACFL poisoning defense."""

  def __init__(
      self,
      acfl_config: Optional[ACFLConfig] = None,
      malicious_clients: Optional[Dict[str, bool]] = None,
      probe_file: Optional[str] = None,
      **kwargs,
  ):
      super().__init__(**kwargs)
      self.acfl_config = acfl_config or ACFLConfig()
      if malicious_clients:
          self.acfl_config.ground_truth_malicious = malicious_clients

      trust_path = os.path.join(
          getattr(config, "CHECKPOINT_DIR", "checkpoints"),
          "acfl_trust_scores.json",
      )
      self.acfl_config.trust_score_path = trust_path

      probe_data = self._load_probe_set(probe_file)

      self.acfl_defense = ACFLDefense(
          config=self.acfl_config,
          model=self.model,
          probe_data=probe_data,
          device=torch.device("cpu"),
          learning_mode=self.learning_mode,
      )

      self.spoofing_detector: Optional[SpoofingDetector] = None
      if self.acfl_config.enable_layer3:
          self.spoofing_detector = SpoofingDetector(
              model=self.model,
              threshold=self.acfl_config.spoofing_detection_threshold,
              cross_modal_weight=self.acfl_config.cross_modal_weight,
              probe_blend_weight=self.acfl_config.layer3_probe_blend_weight,
              learning_mode=self.learning_mode,
              probe_data=probe_data,
              device=torch.device("cpu"),
          )

      self.client_mission_context: Dict[str, Dict[str, float]] = {}
      self.acfl_round_reports: List[Dict] = []

      acfl_logger.info(
          "ACFL Server initialized: layer1=%s, layer2=%s, layer3=%s",
          self.acfl_config.enable_layer1,
          self.acfl_config.enable_layer2,
          self.acfl_config.enable_layer3,
      )

  def _load_probe_set(self, probe_file):
      """Load a counterfactual probe set generated by generate_probe_set.py."""
      if not probe_file:
          return None
      if not os.path.exists(probe_file):
          acfl_logger.warning("Probe file not found: %s (Layer 1 counterfactual "
                              "validation disabled)", probe_file)
          return None
      try:
          payload = torch.load(probe_file, map_location="cpu", weights_only=False)
          probe_data = payload.get("probe_data", payload)
          acfl_logger.info(
              "Loaded probe set from %s (%d scenarios: %s)",
              probe_file, len(probe_data), ", ".join(probe_data.keys()),
          )
          return probe_data
      except Exception as e:
          acfl_logger.error("Failed to load probe set %s: %s", probe_file, e)
          return None

  async def handle_submit_update(self, request):
      """Receive updates; extract mission-context metadata from headers."""
      client_id = request.headers.get("X-Client-ID")

      mission_ctx = {}
      for header_key, feature in [
          ("X-GNSS-IMU-Consistency", "gnss_imu_consistency"),
          ("X-MAVLink-Consistency", "mavlink_state_consistency"),
          ("X-Link-Health", "link_health"),
          ("X-Attack-Ratio", "attack_label_ratio"),
      ]:
          val = request.headers.get(header_key)
          if val is not None:
              try:
                  mission_ctx[feature] = float(val)
              except ValueError:
                  pass

      if client_id and mission_ctx:
          self.client_mission_context[client_id] = mission_ctx

      return await super().handle_submit_update(request)

  async def _aggregate_and_update(self):
      """Override aggregation to use ACFL defense pipeline."""
      import time

      if not self.client_weights:
          return

      try:
          self.current_operation = "acfl_defense_aggregation"
          self.operation_start_time = time.time()

          client_ids = list(self.client_weights.keys())
          weights_list = [self.client_weights[cid] for cid in client_ids]
          samples_list = [self.client_samples[cid] for cid in client_ids]
          global_weights = {
              key: tensor.clone() for key, tensor in self.model.get_weights().items()
          }
          client_weights = [
              {key: tensor.clone() for key, tensor in cw.items()}
              for cw in weights_list
          ]

          mission_context = {}
          for cid in client_ids:
              ctx = self.client_mission_context.get(cid, {}).copy()
              loss = self.client_losses.get(cid, 0.0)
              ctx["local_validation_loss"] = max(0.0, 1.0 - min(loss, 1.0))
              mission_context[cid] = ctx

          aggregated_weights = self.acfl_defense.defend_and_aggregate(
              client_ids=client_ids,
              client_weights=client_weights,
              global_weights=global_weights,
              client_losses=self.client_losses,
              mission_context=mission_context,
              client_samples=samples_list,
          )

          self.model.set_weights(aggregated_weights)

          layer1_trust = self.acfl_defense.trust_history[-1] if self.acfl_defense.trust_history else {}
          breakdown = self.acfl_defense.get_trust_breakdown(
              client_ids, client_weights, global_weights,
              layer1_trust, mission_context,
          )

          avg_loss = sum(self.client_losses.values()) / len(self.client_losses)
          self.round_losses.append(avg_loss)

          report = {
              "round": self.current_round + 1,
              "trust_scores": layer1_trust,
              "trust_breakdown": breakdown,
              "aggregation_guard": getattr(
                  self.acfl_defense,
                  "last_aggregation_guard",
                  None,
              ),
              "update_norm_rejection": getattr(
                  self.acfl_defense,
                  "last_update_norm_rejection",
                  None,
              ),
              "robust_norm_soft_cap": getattr(
                  self.acfl_defense,
                  "last_robust_norm_soft_cap",
                  None,
              ),
              "layer1_layer2_gating": getattr(
                  self.acfl_defense,
                  "last_layer1_layer2_gating",
                  None,
              ),
              "aggregation_diagnostics": getattr(
                  self.acfl_defense.layer2,
                  "last_aggregation_diagnostics",
                  {},
              ) if self.acfl_defense.layer2 is not None else {},
              "avg_loss": avg_loss,
          }
          self.acfl_round_reports.append(report)

          if report["aggregation_guard"] and report["aggregation_guard"].get("skipped"):
              acfl_logger.warning(
                  "ACFL Round %d skipped aggregation: %s",
                  self.current_round + 1,
                  report["aggregation_guard"].get("reason"),
              )
          elif report.get("update_norm_rejection", {}).get("rejected_clients"):
              rejected = report["update_norm_rejection"]["rejected_clients"]
              acfl_logger.warning(
                  "ACFL Round %d rejected %d update(s) by norm: %s",
                  self.current_round + 1,
                  len(rejected),
                  [r.get("client_id") for r in rejected],
              )
              acfl_logger.info(
                  "ACFL Round %d complete - Trust: %s, Avg Loss: %.6f",
                  self.current_round + 1,
                  {k: f"{v:.3f}" for k, v in layer1_trust.items()},
                  avg_loss,
              )
          else:
              acfl_logger.info(
                  "ACFL Round %d complete - Trust: %s, Avg Loss: %.6f",
                  self.current_round + 1,
                  {k: f"{v:.3f}" for k, v in layer1_trust.items()},
                  avg_loss,
              )

          self.current_round += 1
          self.client_weights.clear()
          self.client_samples.clear()
          self.client_losses.clear()
          self.ready_clients.clear()

          self._save_checkpoint()
          self._save_acfl_report()

          self.current_operation = "idle"
          self.operation_start_time = None

      except Exception as e:
          acfl_logger.error("ACFL aggregation error: %s", e, exc_info=True)
          self.current_operation = "error"
          self.operation_details = {"error": str(e)}

  def _save_acfl_report(self):
      report_dir = getattr(config, "CHECKPOINT_DIR", "checkpoints")
      os.makedirs(report_dir, exist_ok=True)
      path = os.path.join(report_dir, "acfl_round_reports.json")
      with open(path, "w") as f:
          json.dump(self.acfl_round_reports, f, indent=2)

  async def handle_status(self, request):
      """Extend status with ACFL defense metrics."""
      import time

      mode_counts = {}
      for mode in self.client_modes.values():
          mode_counts[mode] = mode_counts.get(mode, 0) + 1

      loss_history_dict = {
          cid: [float(loss) for loss in losses]
          for cid, losses in self.loss_history.items()
      }

      operation_duration = None
      if self.operation_start_time is not None:
          operation_duration = time.time() - self.operation_start_time

      body = {
          "current_round": self.current_round,
          "registered_clients": len(self.registered_clients),
          "ready_clients": len(self.ready_clients),
          "total_expected": self.num_clients,
          "aggregation_strategy": "acfl",
          "learning_mode": self.learning_mode,
          "output_size": self.output_size,
          "client_modes": mode_counts,
          "loss_history": loss_history_dict,
          "round_losses": [float(loss) for loss in self.round_losses],
          "current_client_losses": {
              cid: float(loss) for cid, loss in self.client_losses.items()
          },
          "current_operation": self.current_operation,
          "operation_duration": (
              round(operation_duration, 3) if operation_duration is not None else None
          ),
          "operation_details": self.operation_details,
      }

      body["acfl"] = {
          "enabled": True,
          "layer1": self.acfl_config.enable_layer1,
          "layer2": self.acfl_config.enable_layer2,
          "layer3": self.acfl_config.enable_layer3,
          "rounds_defended": self.acfl_defense.round_number,
          "summary": self.acfl_defense.summary(),
      }

      if self.acfl_defense.trust_history:
          body["acfl"]["latest_trust_scores"] = self.acfl_defense.trust_history[-1]

      return web.json_response(body)

  async def handle_detect_spoofing(self, request):
      """Layer 3 endpoint: run spoofing detection on sensor data."""
      if not self.spoofing_detector:
          return web.json_response({"error": "Layer 3 not enabled"}, status=400)

      import pickle
      data = await request.read()
      payload = pickle.loads(data)
      sensor_window = payload["sensor_window"]
      command_state = payload.get("command_state")

      result = self.spoofing_detector.detect(sensor_window, command_state)
      return web.json_response(result)

  def create_app(self):
      from aiohttp import web
      app = super().create_app()
      app.router.add_post("/detect_spoofing", self.handle_detect_spoofing)
      return app


